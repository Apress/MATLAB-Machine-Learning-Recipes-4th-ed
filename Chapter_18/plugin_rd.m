function hRD = plugin_rd()
hRD = hdlcoder.ReferenceDesign('SynthesisTool', 'Xilinx Vivado');
hRD.ReferenceDesignName = 'ZedBoard DL HDL Reference Design';
hRD.BoardName = 'ZedBoard';
hRD.SupportedToolVersion = {'2024.1'};
hRD.addIPRepository('IPListFunction','hdlverifier.fpga.vivado.iplist');
hRD.addCustomVivadoDesign( ...
    'CustomBlockDesignTcl', 'system_top.tcl', ...
    'VivadoBoardPart',      'avnet.com:zedboard:part0:1.4');
hRD.addDeviceTree('axilite.dtsi');
hRD.addClockInterface( ...
    'ClockConnection',     'core_clkwiz/clk_out1', ...
    'ResetConnection',     'sys_core_rstgen/peripheral_aresetn', ...
    'DefaultFrequencyMHz', 50, ...
    'MinFrequencyMHz',     5, ...
    'MaxFrequencyMHz',     500, ...
    'ClockModuleInstance', 'core_clkwiz', ...
    'ClockNumber',         1);
hRD.addAXI4SlaveInterface( ...
    'InterfaceConnection',    'axi_cpu_interconnect/M00_AXI', ...
    'BaseAddress',            {'0x400D0000','0x400D0000'}, ...
    'MasterAddressSpace',     {'sys_cpu/Data','hdlverifier_axi_mana_0/axi4m'}, ...
    'IDWidth',                13, ...
    'HasProcessorConnection', true, ...
    'DeviceTreeBusNode',      '&fpga_axi');
hRD.addFPGADataCaptureInterface( ...
    'AllowedConnectivityTypes', {'JTAG','PS Ethernet','USB Ethernet'}, ...
    'ManagerConnection',        'axi_cpu_interconnect/M01_AXI', ...
    'ManagerAddressSegments',   {'sys_cpu/Data',hex2dec('0x50000000'),hex2dec('0x00100000')}, ...
    'ManagerClockConnection',   'core_clkwiz/clk_out1', ...
    'ManagerResetConnection',   'sys_core_rstgen/peripheral_aresetn');
hRD.addAXI4MasterInterface( ...
    'InterfaceID',            'AXI4 Master Activation Data', ...
    'ReadSupport',            true, ...
    'WriteSupport',           true, ...
    'MaxDataWidth',           128, ...
    'AddrWidth',              32, ...
    'DefaultReadBaseAddr',    hex2dec('10000000'), ...
    'DefaultWriteBaseAddr',   hex2dec('14000000'), ...
    'InterfaceConnection',    'axi_interconnect_0/S00_AXI', ...
    'TargetAddressSegments',  {{'sys_cpu/S_AXI_HP0/HP0_DDR_LOWOCM',hex2dec('10000000'),hex2dec('04000000')}});
hRD.addAXI4MasterInterface( ...
    'InterfaceID',            'AXI4 Master Weight Data', ...
    'ReadSupport',            true, ...
    'WriteSupport',           false, ...
    'MaxDataWidth',           128, ...
    'AddrWidth',              32, ...
    'DefaultReadBaseAddr',    hex2dec('18000000'), ...
    'InterfaceConnection',    'axi_interconnect_0/S01_AXI', ...
    'TargetAddressSegments',  {{'sys_cpu/S_AXI_HP0/HP0_DDR_LOWOCM',hex2dec('18000000'),hex2dec('04000000')}});
hRD.addAXI4MasterInterface( ...
    'InterfaceID',            'AXI4 Master Debug', ...
    'ReadSupport',            true, ...
    'WriteSupport',           true, ...
    'MaxDataWidth',           64, ...
    'AddrWidth',              32, ...
    'DefaultReadBaseAddr',    hex2dec('1E000000'), ...
    'DefaultWriteBaseAddr',   hex2dec('1F000000'), ...
    'InterfaceConnection',    'axi_interconnect_0/S02_AXI', ...
    'TargetAddressSegments',  {{'sys_cpu/S_AXI_HP0/HP0_DDR_LOWOCM',hex2dec('1E000000'),hex2dec('01000000')}});
hRD.registerDeepLearningTargetInterface("JTAG");
hRD.registerDeepLearningMemoryAddressSpace(hex2dec('10000000'), hex2dec('10000000'));
hRD.GenerateIPCoreDeviceTreeNodes = true;
end