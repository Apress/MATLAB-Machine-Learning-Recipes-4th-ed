%% SMARTWIPERSSYSTEM Create and output the windshield wipers fuzzy system. 
% Will run a demo and plot the input and outputs, and display the rules if
% called with no output.
%
%% Form:
%      SmartWipersSystem;   % built-in demo
%  d = SmartWipersSystem
%% Inputs:
%  None.
%
%% Outputs
%  d    (.)   Fuzzy system
%% See also
% BuildFuzzySystem, FuzzyPlot, PrintFuzzyRules

function d = SmartWipersSystem

d = BuildFuzzySystem(...
    'id',1,...
    'input comp',{'Dry'  'Drizzle'  'Wet'} ,...
    'input type', {@TrapezoidMF  @TriangleMF  @TrapezoidMF} ,...
    'input params',{[0 0 10 50]  [40 50]  [50 90 101 101]},...
    'input range',[0 100],...
    'input name','Wetness',...
    'id',2,...
    'input comp',{'Light'  'Medium'  'Heavy'},...
    'input type',{@TriangleMF  @TriangleMF  @TrapezoidMF},...
    'input params',{[100 0]  [100 100]  [100 200 251 251]},...
    'input name','Intensity',...
    'input range',[0 250],...
    'id',1,...
    'output comp',{'Stop'  'Slow'  'Fast'},...
    'output type',{@TrapezoidMF  @TrapezoidMF  @TrapezoidMF},...
    'output params',{[0 0 4 1]  [3 4.5000 6.5 10.000]  [9 9.5000 10.1000 10.1000]},...
    'output name','Speed',...
    'output range',[0 10],...
    'id',2,...
    'output comp',{'Zero'  'Short'  'Long'},...
    'output type',{@TriangleMF  @TrapezoidMF  @TrapezoidMF},...
    'output params',{[6 0]  [0 6 12 18]  [12 18 20.1000 20.1000]},...
    'output name','Interval',...
    'output range',[0 20],...
    'id',1,...
    'rule input',[1 1],...
    'rule output',[1 3],...
    'rule operator',@FuzzyAND,...
    'id',2,...
    'rule input',[1 2],...
    'rule output',[2 3],...
    'rule operator',@FuzzyAND,...
    'id',3,...
    'rule input',[1 3],...
    'rule output',[2 2],...
    'rule operator',@FuzzyAND,...
    'id',4,...
    'rule input',[2 1],...
    'rule output',[2 3],...
    'rule operator',@FuzzyAND,...
    'id',5,...
    'rule input',[2 2],...
    'rule output',[2 2],...
    'rule operator',@FuzzyAND,...
    'id',6,...
    'rule input',[2 3],...
    'rule output',[2 1],...
    'rule operator',@FuzzyAND,...
    'id',7,...
    'rule input',[3 1],...
    'rule output',[2 2],...
    'rule operator',@FuzzyAND,...
    'id',8,...
    'rule input',[3 2],...
    'rule output',[3 2],...
    'rule operator',@FuzzyAND,...
    'id',9,...
    'rule input',[3 3],...
    'rule output',[3 1],...
    'rule operator',@FuzzyAND,...
    'implicate',@ClipIMP,...
    'aggregate',@max,...
    'defuzzify',@CentroidDF,...
    'data',[100 100]);

if nargout==0
  FuzzyPlot( d.input(1) );
  FuzzyPlot( d.input(2) );
  FuzzyPlot( d.output(1) );
  FuzzyPlot( d.output(2) );
  PrintFuzzyRules(d);
  disp(d)
  clear d
end


