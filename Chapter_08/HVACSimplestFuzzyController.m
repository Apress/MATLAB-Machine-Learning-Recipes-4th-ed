%% Simplest fuzzy HVAC with discrete output
% This version considers only the inside temperature and the set point. The
% HVAC output can only be on or off, either AC or heat at the maximum
% operating value.
%% Form:
%  d     = HVACFuzzyController('initialize',qMax)
%  [d,q] = HVACFuzzyController('update',tE,t,tSet,d)

function [q,cat] = HVACSimplestFuzzyController(mode,tI,tSet,d)

persistent qMax;

if nargin==0
  Demo;
  return;
end

%% Initialize
% Create the system
switch mode
  case 'initialize'
    if nargin<2
      qMax = 1000;
    else 
      qMax = tI;
    end

    % External and set point temps
    bT = [0 4 6 10]; % 4 vertices of each input trapezoid
    oT = [10 15 20 25 30];
    iP = cell(1,5);
    for k  = 1:5
      iP{k} =  bT + oT(k);
    end

    % Define an arbitrary output range, 0 to 6 for the mode
    oP = {[0 0 1.5 2.5] [1.5 2 4 4.5] [3.5 4.5 6 6]};

    d = BuildFuzzySystem(...
      'id',1,...
      'input comp',{'Cold'  'Cool' 'Temperate' 'Warm'  'Hot'} ,...
      'input type', {@TrapezoidMF  @TrapezoidMF @TrapezoidMF  @TrapezoidMF @TrapezoidMF} ,...
      'input params',iP,...
      'input range',[bT(1) + oT(1) + eps bT(4)+ oT(5) - eps],...
      'input name','Temperature',...
      'id',2,...
      'input comp',{'Cold'  'Cool' 'Temperate' 'Warm'  'Hot'} ,...
      'input type', {@TrapezoidMF  @TrapezoidMF @TrapezoidMF  @TrapezoidMF @TrapezoidMF} ,...
      'input params',iP,...
      'input range',[bT(1) + oT(1) bT(4)+ oT(5)],...
      'input name','Target',...
      'id',1,...
      'output comp',{'AC'  'None'  'Heat'},...
      'output type',{@TrapezoidMF  @TrapezoidMF  @TrapezoidMF},...
      'output params',oP,...
      'output name','Setting',...
      'output range',[0 6],...
      'implicate',@ClipIMP,...
      'aggregate',@max,...
      'defuzzify',@CentroidDF,...
      'id',1,...
      'rule input',[1 1],...
      'rule output',2,...
      'rule operator',@FuzzyAND,...
      'id',2,...
      'rule input',[2 2],...
      'rule output',2,...
      'rule operator',@FuzzyAND,...
      'id',3,...
      'rule input',[3 3],...
      'rule output',2,...
      'rule operator',@FuzzyAND,...
      'id',4,...
      'rule input',[4 4],...
      'rule output',2,...
      'rule operator',@FuzzyAND,...
      'id',5,...
      'rule input',[5 5],...
      'rule output',2,...
      'rule operator',@FuzzyAND,...
      'id',6,...
      'rule input',[1 2],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',7,...
      'rule input',[1 3],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',8,...
      'rule input',[1 4],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',9,...
      'rule input',[1 5],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',10,...
      'rule input',[2 1],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',11,...
      'rule input',[2 3],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',12,...
      'rule input',[2 4],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',13,...
      'rule input',[2 5],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',14,...
      'rule input',[3 1],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',15,...
      'rule input',[3 2],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',16,...
      'rule input',[3 4],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',17,...
      'rule input',[3 5],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',18,...
      'rule input',[4 1],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',19,...
      'rule input',[4 2],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',20,...
      'rule input',[4 3],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',21,...
      'rule input',[4 5],...
      'rule output',3,...
      'rule operator',@FuzzyAND,...
      'id',22,...
      'rule input',[5 1],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',23,...
      'rule input',[5 2],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',24,...
      'rule input',[5 3],...
      'rule output',1,...
      'rule operator',@FuzzyAND,...
      'id',25,...
      'rule input',[5 4],...
      'rule output',1,...
      'rule operator',@FuzzyAND);

    q = d; % map output

  case 'update'
    kToC  = 273;
    tF    = [tI,tSet]-kToC;
    cat   = FuzzyInference(tF, d);

    % use the cat for on/off only and use the max Q
    if( cat <= 2 )
      q = -qMax;
    elseif( cat < 4 )
      q = 0;
    else
      q = qMax;
    end
end

end

%% Demonstrate the controller
function Demo

d = HVACSimplestFuzzyController('initialize');

%% Plot
FuzzyPlot( d.input(1) );
FuzzyPlot( d.input(2) );
FuzzyPlot( d.output(1) );

kToC  = 273; % Kelvin to Celsius
tAct = linspace(d.input(1).range(1)+1e-12,d.input(1).range(2)-1e-12,51) + kToC;
tSet = linspace(d.input(2).range(1)+1e-12,d.input(2).range(2)-1e-12,31) + kToC;

q = zeros(length(tAct),length(tSet));
out = zeros(length(tAct),length(tSet));
for j = 1:length(tAct)
  for k = 1:length(tSet)
    [q(j,k),out(j,k)] = HVACSimplestFuzzyController('update',tAct(j),tSet(k),d);
  end
end

NewFigure('HVAC Mode from Fuzzy Logic');
surf(tAct,tSet,out')
xlabel('Actual Temp')
ylabel('Target Temp')
title('HVAC Setting')

NewFigure('HVAC Output from Fuzzy Logic');
surf(tAct,tSet,q')
xlabel('Actual Temp')
ylabel('Target Temp')
title('HVAC Output (W)')

end


